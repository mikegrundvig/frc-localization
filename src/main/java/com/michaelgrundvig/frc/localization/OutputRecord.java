package com.michaelgrundvig.frc.localization;

import io.soabase.recordbuilder.core.RecordBuilder;
import java.lang.annotation.ElementType;
import java.lang.annotation.Inherited;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks one of localization's outputs (what an update says), built by name through a builder
 * generated at compile time: {@code
 * TagVerdict.builder().tag(26).verdict(Verdict.ACCEPTED)...build()}.
 *
 * <p>Unlike a configuration record's builder, this one lets a value be left out, so a value added
 * later breaks no caller: a collection left out is empty, an {@code Optional} empty, a number the
 * record documents as NaN when not compared is NaN, and anything the record can't do without is
 * refused when it's built.
 *
 * <p>Generated by <a href="https://github.com/Randgalt/record-builder">RecordBuilder</a>; a record
 * {@code Name} gets {@code NameBuilder}, a nested record {@code Outer.Name} gets {@code
 * OuterNameBuilder}.
 */
@RecordBuilder.Template(
    options =
        @RecordBuilder.Options(
            builderMode = RecordBuilder.BuilderMode.STANDARD,
            addStaticBuilder = false, // no positional shortcut
            addClassRetainedGenerated = true, // lets the coverage report skip generated code
            // A collection left out is empty; one given keeps its order.
            useUnmodifiableCollections = true,
            emptyDefaultForOptional = true))
@Retention(RetentionPolicy.CLASS)
@Target(ElementType.TYPE)
@Inherited
public @interface OutputRecord {}
